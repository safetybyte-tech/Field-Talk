import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const bundle = await build({entryPoints:['src/utils/talkDocument.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const module = {exports:{}};
new Function('require','module','exports',bundle.outputFiles[0].text)(createRequire(import.meta.url),module,module.exports);
const {createTalkPdf,buildTalkDocumentHtml} = module.exports;
const source='https://www.ecfr.gov/current/title-29/section-1926.501';
const talk={title:'QA export fixture',date:'2026-09-07',location:'Synthetic roof',projectNumber:'QA',weather:'Clear',supervisor:'QA Foreman',supervisorEmail:'qa@example.com',attendees:[],recipients:[],content:JSON.stringify({i:'Synthetic export test.',hazards:['Roof edge'],practices:['Review the plan'],ppe:['Harness'],sif:['Use approved fall protection'],manual:[],q:['What is the rescue plan?'],citations:[{citation:'1926.501',source_url:source},{citation:'bad',source_url:'javascript:alert(1)'}]}),harness:{version:'harness-v2',retrieval:{status:'grounded',sourceCount:1,citations:['1926.501']},validation:[{id:'fixture',status:'review_required',message:'Synthetic review warning'}],persisted:true}};
const pdf=createTalkPdf(talk);
const output=pdf.output();
assert.ok(output.includes(source));
assert.ok(output.includes('/URI'));
assert.ok(output.includes('Synthetic review warning'));
assert.ok(!output.includes('javascript:'));
const html=buildTalkDocumentHtml(talk);
assert.ok(html.includes(source)); assert.ok(!html.includes('javascript:'));
writeFileSync('/private/tmp/v2-export-fixture.pdf',Buffer.from(pdf.output('arraybuffer')));
console.log('PASS: PDF links, review warning, HTML references, unsafe URL exclusion.');
